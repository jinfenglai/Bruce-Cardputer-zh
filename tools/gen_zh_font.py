#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generate the embedded 12px / 16px Chinese bitmap fonts used by the
Bruce Chinese localization layer.

Source font : Noto Sans SC (SIL Open Font License 1.1)
Charset     : GB2312 (6763 hanzi + symbols, 7445 codepoints) + every
              character that appears in lang/zh_CN.json.

Usage:
    python tools/gen_zh_font.py [--font PATH] [--out DIR]

The generated .cpp files are committed to the repository, so a normal
firmware build does not need Python or the font.  Re-run this script only
when the charset or the source font changes.
"""
import argparse
import json
import os
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_FONT = r"C:\Windows\Fonts\NotoSansSC-VF.ttf"
OUT_DIR = os.path.join(ROOT, "src", "core", "lang")
LANG_JSON = os.path.join(ROOT, "lang", "zh_CN.json")

SIZES = {
    12: dict(weight="Regular", threshold=110, rows=12, row_bytes=2),
    16: dict(weight="Medium", threshold=110, rows=16, row_bytes=2),
}


def gb2312_charset():
    chars = []
    for hi in range(0xA1, 0xF8):
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes((hi, lo)).decode("gb2312")
            except UnicodeDecodeError:
                continue
            if ch not in chars:
                chars.append(ch)
    return chars


def load_font(path, size, weight):
    font = ImageFont.truetype(path, size)
    try:
        font.set_variation_by_name(weight)
    except Exception:
        # static font (no variation axes) - keep the face as-is
        pass
    return font


def render_glyph(ch, size, font, threshold):
    img = Image.new("L", (size, size), 0)
    ImageDraw.Draw(img).text((size / 2, size / 2), ch, font=font, fill=255, anchor="mm")
    return img.point(lambda p: 255 if p >= threshold else 0, mode="1")


def pack_glyph(img, size):
    rows = []
    for y in range(size):
        bits = 0
        for x in range(size):
            if img.getpixel((x, y)):
                bits |= 1 << (size - 1 - x)
        rows.append(bits)
    out = bytearray()
    for bits in rows:
        out.append((bits >> 8) & 0xFF)
        out.append(bits & 0xFF)
    return bytes(out)


def c_array(name, data, per_line=12):
    lines = [f"const uint8_t {name}[{len(data)}] = {{"]
    for i in range(0, len(data), per_line):
        chunk = data[i : i + per_line]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def c_array16(name, values, per_line=12):
    lines = [f"const uint16_t {name}[{len(values)}] = {{"]
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append("    " + ", ".join(f"0x{v:04X}" for v in chunk) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default=DEFAULT_FONT)
    ap.add_argument("--out", default=OUT_DIR)
    args = ap.parse_args()

    if not os.path.exists(args.font):
        sys.exit(f"font not found: {args.font}")

    charset = gb2312_charset()
    with open(LANG_JSON, encoding="utf-8") as f:
        translations = json.load(f)
    extra = set()
    for v in translations.values():
        for ch in v:
            if ord(ch) > 0x7F:
                extra.add(ch)
    for ch in extra:
        if ch not in charset:
            charset.append(ch)
    charset.sort(key=lambda c: ord(c))

    missing = [c for c in extra if ord(c) > 0x7F and c not in charset]
    # (extra chars were just appended, so missing is only informative)
    print(f"charset: {len(charset)} codepoints, extra from translations: {len(extra)}")

    os.makedirs(args.out, exist_ok=True)
    uni = [ord(ch) for ch in charset]

    with open(os.path.join(args.out, "zh_font_unicode.cpp"), "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_zh_font.py - do not edit.\n")
        f.write("#if defined(BRUCE_LANG_ZH)\n")
        f.write('#include "zh_font.h"\n\n')
        f.write(f"const uint16_t ZH_FONT_COUNT = {len(charset)};\n\n")
        f.write(c_array16("zh_unicode", uni, 12))
        f.write("\n#endif\n")
        f.write("\n")

    font_path = args.font
    for size, cfg in SIZES.items():
        font = load_font(font_path, size, cfg["weight"])
        data = bytearray()
        empty = 0
        for ch in charset:
            img = render_glyph(ch, size, font, cfg["threshold"])
            if img.getbbox() is None and ch.strip():
                empty += 1
            data += pack_glyph(img, size)
        name = f"zh_font{size}"
        path = os.path.join(args.out, f"{name}.cpp")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("// Generated by tools/gen_zh_font.py - do not edit.\n")
            f.write("#if defined(BRUCE_LANG_ZH)\n")
            f.write('#include "zh_font.h"\n\n')
            f.write(c_array(name, bytes(data), 12))
            f.write("\n#endif\n")
            f.write("\n")
        print(f"{name}: {len(data)} bytes, empty glyphs: {empty}")

    meta = {
        "source_font": os.path.basename(font_path),
        "license": "SIL Open Font License 1.1",
        "charset": "GB2312 + chars used by lang/zh_CN.json",
        "count": len(charset),
        "sizes": {str(k): v["rows"] for k, v in SIZES.items()},
    }
    with open(os.path.join(args.out, "zh_font_meta.json"), "w", encoding="utf-8", newline="\n") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print("done ->", args.out)


if __name__ == "__main__":
    main()
